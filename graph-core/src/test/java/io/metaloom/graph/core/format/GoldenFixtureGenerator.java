package io.metaloom.graph.core.format;

import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.Properties;

import io.metaloom.graph.core.api.GraphStore;
import io.metaloom.graph.core.api.GraphStoreOptions;
import io.metaloom.graph.core.api.StoreFormat;
import io.metaloom.graph.core.api.VerifyLevel;
import io.metaloom.graph.core.fixture.StoreFiles;

/**
 * Writes the golden fixture for {@link StoreFormat#CURRENT_VERSION}: {@code format/v<N>/} under the test resources.
 *
 * <pre>
 * tools/golden-fixture.sh             # writes graph-core/src/test/resources/format/v&lt;CURRENT&gt;/
 * tools/golden-fixture.sh --replace   # only for the current version, only if its format did not change
 * </pre>
 *
 * <p>
 * <b>A fixture for an older version is never regenerated</b> — this class could not do it anyway, since it writes
 * the current format — and it refuses to overwrite the current one without {@code --replace}. The fixture of a version
 * is the evidence of what that version's bytes were; rewriting it with newer code would quietly turn the test that
 * migrates it into a test that migrates nothing. {@code --replace} exists for one case: extending what the current
 * fixture covers before the format has moved on. spec/MIGRATION.md section 6.
 * </p>
 */
public final class GoldenFixtureGenerator {

	private GoldenFixtureGenerator() {
	}

	public static void main(String[] args) throws IOException {
		Path out = null;
		boolean replace = false;
		for (String arg : args) {
			if (arg.equals("--replace")) {
				replace = true;
			} else if (arg.startsWith("--out=")) {
				out = Path.of(arg.substring("--out=".length()));
			} else {
				System.err.println("Usage: GoldenFixtureGenerator [--out=<format directory>] [--replace]");
				System.exit(2);
			}
		}
		if (out == null) {
			out = defaultOut();
		}
		Path written = generate(out, replace);
		System.out.println("Wrote " + written);
		try (var files = Files.list(written)) {
			for (Path file : (Iterable<Path>) files.sorted()::iterator) {
				System.out.printf("  %-20s %,d bytes%n", file.getFileName(), Files.size(file));
			}
		}
	}

	private static Path defaultOut() {
		for (String candidate : new String[] { "src/test/resources/format", "graph-core/src/test/resources/format" }) {
			Path path = Path.of(candidate);
			if (Files.isDirectory(path.getParent())) {
				return path;
			}
		}
		throw new IllegalStateException("Run from the repository root or from graph-core, or pass --out=");
	}

	/** Generates the current version's fixture under {@code formatDirectory} and returns its directory. */
	public static Path generate(Path formatDirectory, boolean replace) throws IOException {
		int version = StoreFormat.CURRENT_VERSION;
		Path target = formatDirectory.resolve("v" + version);
		if (Files.exists(target) && !replace) {
			throw new IllegalStateException(target + " exists. A fixture is never regenerated by default: if the"
				+ " format changed, bump StoreFormat.CURRENT_VERSION and generate the next version's fixture instead; if"
				+ " only the fixture's content grew and the format did not change, pass --replace.");
		}
		Path work = Files.createTempDirectory("golden-fixture-");
		try {
			Path root = work.resolve("root");
			Path store = root.resolve(GoldenContent.DATABASE);
			GraphStoreOptions options = GoldenContent.options();
			try (GraphStore graph = GraphStore.open(store, options)) {
				GoldenContent.write(graph);
			}
			GoldenContent.writeAuth(root);

			// Read back through a fresh open, so expected.txt is what this build reads from these bytes rather than
			// what it believed it wrote.
			String expected;
			try (GraphStore graph = GraphStore.open(store, options)) {
				graph.verify(VerifyLevel.FULL);
				expected = GoldenContent.canonical(graph);
			}
			String expectedAuth = GoldenContent.canonicalAuth(root);
			if (StoreFormat.inspect(store).version() != version) {
				throw new IllegalStateException("The store reads as version " + StoreFormat.inspect(store).version());
			}

			if (Files.exists(target)) {
				StoreFiles.deleteRecursively(target);
			}
			Files.createDirectories(target);
			GoldenFixtures.zip(root, target.resolve(GoldenFixtures.ZIP));
			Files.writeString(target.resolve(GoldenFixtures.EXPECTED), expected, StandardCharsets.UTF_8);
			Files.writeString(target.resolve(GoldenFixtures.EXPECTED_AUTH), expectedAuth, StandardCharsets.UTF_8);

			Properties properties = new Properties();
			properties.setProperty("version", Integer.toString(version));
			properties.setProperty("generated", Instant.now().toString());
			properties.setProperty("commit", gitHead());
			properties.setProperty("database", GoldenContent.DATABASE);
			properties.setProperty("pageSize", Integer.toString(options.pageSize()));
			properties.setProperty("segmentCapacity", Long.toString(options.segmentCapacity()));
			properties.setProperty("walSegmentBytes", Long.toString(options.walSegmentBytes()));
			properties.setProperty("vectorDimensions", Integer.toString(options.vectorDimensions()));
			try (OutputStream out = Files.newOutputStream(target.resolve(GoldenFixtures.PROPERTIES))) {
				properties.store(out, "Golden fixture for store format version " + version
					+ ". Never regenerate an older version's fixture. spec/MIGRATION.md section 6.");
			}
			return target;
		} finally {
			StoreFiles.deleteRecursively(work);
		}
	}

	private static String gitHead() {
		try {
			Process process = new ProcessBuilder("git", "rev-parse", "--short", "HEAD").redirectErrorStream(true)
				.start();
			String head = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8).trim();
			return process.waitFor() == 0 ? head : "unknown";
		} catch (IOException | InterruptedException e) {
			return "unknown";
		}
	}
}

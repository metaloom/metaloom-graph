package io.metaloom.graph.core.format;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.io.IOException;
import java.nio.file.Path;
import java.util.List;
import java.util.Properties;

import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import io.metaloom.graph.core.api.Direction;
import io.metaloom.graph.core.api.GraphStore;
import io.metaloom.graph.core.api.StoreFormat;
import io.metaloom.graph.core.api.VerifyLevel;

/**
 * <b>The tripwire for the on-disk format.</b> A store written by the build that defined the current format version is
 * committed under {@code src/test/resources/format/v<N>/}, and this build must open it and read back exactly what that
 * build read.
 *
 * <p>
 * Change a record layout, a codec, a dictionary file or a page header without bumping
 * {@link StoreFormat#CURRENT_VERSION} and this fails, because the committed bytes no longer mean what they meant. Bump
 * the version without generating the new fixture and {@link #testThereIsAFixtureForTheCurrentVersion} fails. Bump it
 * and generate one, and {@code GoldenFixtureMigrationTest} fails until a migration step takes the old fixture to the
 * new version. What to do in each case: spec/MIGRATION.md section 6.
 * </p>
 */
@Tag("unit")
public class GoldenFixtureTest {

	@TempDir
	Path tmp;

	private static GoldenFixtures.Fixture current() throws IOException {
		return GoldenFixtures.all().stream().filter(f -> f.version() == StoreFormat.CURRENT_VERSION).findFirst()
			.orElseThrow(() -> new AssertionError("There is no golden fixture for store format version "
				+ StoreFormat.CURRENT_VERSION + ". A format version bump needs one: run tools/golden-fixture.sh and"
				+ " commit graph-core/src/test/resources/format/v" + StoreFormat.CURRENT_VERSION
				+ "/ (spec/MIGRATION.md section 6)"));
	}

	@Test
	public void testThereIsAFixtureForTheCurrentVersion() throws IOException {
		current();
	}

	/** Each fixture is what its directory says: an old fixture regenerated by newer code would read as newer. */
	@Test
	public void testEveryFixtureIsTheVersionItIsFiledUnder() throws IOException {
		List<GoldenFixtures.Fixture> fixtures = GoldenFixtures.all();
		assertFalse(fixtures.isEmpty());
		for (GoldenFixtures.Fixture fixture : fixtures) {
			Properties properties = fixture.properties();
			assertEquals(Integer.toString(fixture.version()), properties.getProperty("version"));
			Path store = fixture.unpack(tmp.resolve("v" + fixture.version()));
			StoreFormat.Info info = StoreFormat.inspect(store);
			assertEquals(fixture.version(), info.version(), "the store inside v" + fixture.version()
				+ " is not at that version. Was an old fixture regenerated? That is never done");
			assertTrue(fixture.version() <= StoreFormat.CURRENT_VERSION, "a fixture from the future");
			assertEquals(properties.getProperty("pageSize"), Integer.toString(info.pageSize()));
			assertEquals(properties.getProperty("segmentCapacity"), Long.toString(info.segmentCapacity()));
			assertEquals(properties.getProperty("vectorDimensions"), Integer.toString(info.vectorDimensions()));
			assertEquals(properties.getProperty("walSegmentBytes"), Long.toString(info.walSegmentBytes()));
		}
	}

	@Test
	public void testTheCurrentFixtureReadsBackExactly() throws IOException {
		GoldenFixtures.Fixture fixture = current();
		Path root = tmp.resolve("root");
		Path store = fixture.unpack(root);
		StoreFormat.Info info = StoreFormat.inspect(store);
		try (GraphStore graph = GraphStore.open(store, info.options())) {
			assertEquals(fixture.expected(), GoldenContent.canonical(graph));
			graph.verify(VerifyLevel.FULL);

			// A few facts stated by hand, so the comparison above is not the only thing that knows what is in here.
			long alice = only(graph.nodesByProperty("uid", "alice"));
			long carol = only(graph.nodesByProperty("uid", "carol"));
			long hub = only(graph.nodesByProperty("uid", "hub"));
			assertEquals(List.of("Person", "Employee"), graph.nodeLabels(alice));
			assertEquals(5, graph.nodeLabels(carol).size(), "two labels past the three a node record holds");
			assertEquals(34L, graph.nodeProperties(alice).getLong("age"));
			assertEquals(40_000, graph.nodeProperties(carol).getString("memoir").length());
			assertTrue(java.nio.file.Files.exists(store.resolve("seg/blob/blob-000001.seg")),
				"the blob kind rolled over into a second segment");
			assertEquals(40, graph.degreeOut(hub));
			assertEquals(4, graph.neighbours(hub, Direction.OUT).stream().filter(e -> e.isMaterialised()).count());
			assertEquals(4, graph.nodesByLabel("Reborn").size());
			assertEquals(6, graph.nodesByLabel("Ghost").size(), "every other ghost was deleted");
		}
		assertEquals(fixture.expectedAuth(), GoldenContent.canonicalAuth(root));
	}

	private static long only(List<Long> ids) {
		assertEquals(1, ids.size(), ids.toString());
		return ids.get(0);
	}
}
